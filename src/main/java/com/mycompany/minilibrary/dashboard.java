    private void updateBookStats() {

        int totalBooks = LibraryData.books.size();
        int availableBooks = 0;
        int borrowedBooks = 0;

        for (Book book : LibraryData.books) {

            if (book.getStatus().equalsIgnoreCase("Available")) {
                availableBooks++;
            }

            if (book.getStatus().equalsIgnoreCase("Borrowed")) {
                borrowedBooks++;
            }
        }

        lblTotalBooks.setText(String.valueOf(totalBooks));
        lblAvailableBooks.setText(String.valueOf(availableBooks));
        lblBorrowedBooks.setText(String.valueOf(borrowedBooks));
    }

