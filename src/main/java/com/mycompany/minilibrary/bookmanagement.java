    private void btnDeleteMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_btnDeleteMouseClicked
        if (selectedRow == -1) {
            javax.swing.JOptionPane.showMessageDialog(this,"Please select a book from the table first.");
            return;
        }

        int choice = javax.swing.JOptionPane.showConfirmDialog(this,"Are you sure you want to delete this book?","Confirm Delete",
                javax.swing.JOptionPane.YES_NO_OPTION);

        if (choice == javax.swing.JOptionPane.YES_OPTION) {

            LibraryData.books.remove(selectedRow);
            displayBooks();

            txtBookId.setText("");
            txtTitle.setText("");
            txtAuthor.setText("");
            txtCategory.setText("");
            cmbStatus.setSelectedIndex(0);

            selectedRow = -1;

            javax.swing.JOptionPane.showMessageDialog(this,"Book deleted successfully!");
        }
    }//GEN-LAST:event_btnDeleteMouseClicked

