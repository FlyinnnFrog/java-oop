    private void displayBooks() {

        DefaultTableModel model
                = (DefaultTableModel) tblBooks.getModel();

        model.setRowCount(0);

        for (Book book : LibraryData.books) {

            Object[] row = {
                book.getBookId(),
                book.getTitle(),
                book.getAuthor(),
                book.getCategory(),
                book.getStatus()
            };

            model.addRow(row);
        }
    }
