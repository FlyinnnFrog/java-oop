    private void tblBooksMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblBooksMouseClicked
        selectedRow = tblBooks.getSelectedRow();

        if (selectedRow >= 0) {

            Book book = LibraryData.books.get(selectedRow);
            txtBookId.setText(book.getBookId());
            txtTitle.setText(book.getTitle());
            txtAuthor.setText(book.getAuthor());
            txtCategory.setText(book.getCategory());
            cmbStatus.setSelectedItem(book.getStatus());
        }
    }//GEN-LAST:event_tblBooksMouseClicked

    private void btnUpdateMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_btnUpdateMouseClicked
        if (selectedRow == -1) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Please select a book from the table first."
            );

            return;
        }

        String id = txtBookId.getText().trim();
        String title = txtTitle.getText().trim();
        String author = txtAuthor.getText().trim();
        String category = txtCategory.getText().trim();
        String status = cmbStatus.getSelectedItem().toString();

        if (id.isEmpty() || title.isEmpty() || author.isEmpty() || category.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please fill in all fields.");
            return;
        }

        Book book = LibraryData.books.get(selectedRow);
        book.setBookId(id);
        book.setTitle(title);
        book.setAuthor(author);
        book.setCategory(category);
        book.setStatus(status);

        displayBooks();

        javax.swing.JOptionPane.showMessageDialog(this, "Book updated successfully!");

        selectedRow = -1;
    }//GEN-LAST:event_btnUpdateMouseClicked

